#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const rootDirectory = process.cwd();
const defaultSvgOutput = "docs/assets/commit-line-delta.svg";
const defaultDataOutput =
	"src/app/(site)/(dev)/internal/playground/commit-history/_data/commit-history.json";
const generatedHistoryCommitSubjects = new Set([
	"chore: update commit history charts",
	"chore: update commit line delta chart",
]);

function getArgument(name, fallback) {
	const index = process.argv.indexOf(name);
	if (index === -1) return fallback;
	const value = process.argv[index + 1];
	if (!value) throw new Error(`Expected a path after ${name}.`);
	return value;
}

const svgOutputPath = getArgument(
	"--svg-output",
	getArgument("--output", defaultSvgOutput),
);
const dataOutputPath = getArgument("--data-output", defaultDataOutput);

const gitOutput = execFileSync(
	"git",
	[
		"log",
		"--reverse",
		"--no-renames",
		"--numstat",
		"--format=commit%x09%H%x09%ad%x09%s",
		"--date=short",
		"HEAD",
	],
	{ cwd: rootDirectory, encoding: "utf8" },
);

const commits = [];
let currentCommit;

for (const line of gitOutput.split("\n")) {
	if (line.startsWith("commit\t")) {
		const [, hash, date, subject] = line.split("\t", 4);
		if (generatedHistoryCommitSubjects.has(subject)) {
			currentCommit = undefined;
			continue;
		}
		currentCommit = { additions: 0, date, deletions: 0, hash, subject };
		commits.push(currentCommit);
		continue;
	}

	const [additions, deletions] = line.split("\t", 3);
	if (!currentCommit || !/^\d+$/.test(additions) || !/^\d+$/.test(deletions)) {
		continue;
	}

	currentCommit.additions += Number(additions);
	currentCommit.deletions += Number(deletions);
}

if (commits.length === 0) {
	throw new Error("No commits were found at HEAD.");
}

let cumulativeNet = 0;
const history = commits.map((commit) => {
	const delta = commit.additions - commit.deletions;
	cumulativeNet += delta;
	return { ...commit, cumulativeNet, delta };
});

const escapeXml = (value) =>
	String(value)
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;")
		.replaceAll('"', "&quot;")
		.replaceAll("'", "&apos;");

const formatDelta = (value) => {
	const absolute = Math.abs(value);
	const compact =
		absolute >= 1000
			? `${(absolute / 1000).toFixed(absolute >= 10_000 ? 0 : 1).replace(/\.0$/, "")}k`
			: String(absolute);

	return value > 0 ? `+${compact}` : value < 0 ? `-${compact}` : "0";
};

const niceStep = (value) => {
	const exponent = Math.floor(Math.log10(Math.max(value, 1)));
	const base = 10 ** exponent;
	const normalized = value / base;
	const multiplier =
		normalized <= 1 ? 1 : normalized <= 2 ? 2 : normalized <= 5 ? 5 : 10;

	return multiplier * base;
};

const dimensions = {
	bottom: 500,
	height: 560,
	left: 92,
	right: 36,
	top: 104,
	width: 1200,
};
const chartWidth = dimensions.width - dimensions.left - dimensions.right;
const chartHeight = dimensions.bottom - dimensions.top;
const deltas = history.map((commit) => commit.delta);
const maximum = Math.max(...deltas.map((delta) => Math.abs(delta)), 1);
const axisMaximum = niceStep(maximum / 4) * 4;
const xFor = (index) =>
	history.length === 1
		? dimensions.left + chartWidth / 2
		: dimensions.left + (index / (history.length - 1)) * chartWidth;
const yFor = (delta) =>
	dimensions.top + ((axisMaximum - delta) / (axisMaximum * 2)) * chartHeight;
const pointList = deltas
	.map((delta, index) => `${xFor(index).toFixed(2)},${yFor(delta).toFixed(2)}`)
	.join(" ");
const midpoint = Math.floor((history.length - 1) / 2);

const gridLines = Array.from({ length: 5 }, (_, index) => {
	const value = axisMaximum - (axisMaximum * 2 * index) / 4;
	const y = yFor(value);
	const emphasized = value === 0;

	return `<line x1="${dimensions.left}" x2="${dimensions.width - dimensions.right}" y1="${y.toFixed(2)}" y2="${y.toFixed(2)}" stroke="${emphasized ? "#64748b" : "#dbe4ee"}" stroke-width="${emphasized ? "1.5" : "1"}" /><text x="${dimensions.left - 14}" y="${(y + 4).toFixed(2)}" text-anchor="end" class="axis-label">${formatDelta(value)}</text>`;
}).join("\n    ");

const circles = history
	.map((commit, index) => {
		const detail = `${commit.hash.slice(0, 7)} · ${commit.date} · ${formatDelta(commit.delta)} lines · ${commit.subject}`;
		const fill =
			commit.delta > 0 ? "#0f766e" : commit.delta < 0 ? "#be123c" : "#64748b";

		return `<circle cx="${xFor(index).toFixed(2)}" cy="${yFor(commit.delta).toFixed(2)}" r="2.8" fill="${fill}"><title>${escapeXml(detail)}</title></circle>`;
	})
	.join("\n    ");

const svg = `<!-- Generated by scripts/generate-commit-line-delta.mjs. Do not edit directly. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${dimensions.width}" height="${dimensions.height}" viewBox="0 0 ${dimensions.width} ${dimensions.height}" role="img" aria-labelledby="title description">
  <title id="title">Net line delta by commit</title>
  <desc id="description">A chronological line chart showing additions minus deletions for ${history.length} commits. Each point represents one commit.</desc>
  <style>
    .heading { fill: #0f172a; font-family: sans-serif; font-size: 24px; font-weight: 700; }
    .subheading { fill: #475569; font-family: sans-serif; font-size: 14px; }
    .axis-label { fill: #64748b; font-family: sans-serif; font-size: 12px; }
  </style>
  <rect width="${dimensions.width}" height="${dimensions.height}" rx="14" fill="#ffffff" />
  <rect x="0.5" y="0.5" width="1199" height="559" rx="13.5" fill="none" stroke="#dbe4ee" />
  <text x="${dimensions.left}" y="42" class="heading">Net line delta by commit</text>
  <text x="${dimensions.left}" y="68" class="subheading">Additions minus deletions · ${history.length} commits · hover a point for commit details</text>
  <g>
    ${gridLines}
  </g>
  <polyline points="${pointList}" fill="none" stroke="#4f46e5" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" />
  <g>
    ${circles}
  </g>
  <g class="axis-label">
    <text x="${xFor(0).toFixed(2)}" y="532" text-anchor="start">${escapeXml(history[0].date)}</text>
    <text x="${xFor(midpoint).toFixed(2)}" y="532" text-anchor="middle">${escapeXml(history[midpoint].date)}</text>
    <text x="${xFor(history.length - 1).toFixed(2)}" y="532" text-anchor="end">${escapeXml(history.at(-1).date)}</text>
    <text x="${dimensions.width - dimensions.right}" y="68" text-anchor="end">Chronological commits →</text>
  </g>
</svg>
`;

function writeOutput(outputPath, content) {
	const resolvedOutput = path.resolve(rootDirectory, outputPath);
	mkdirSync(path.dirname(resolvedOutput), { recursive: true });
	writeFileSync(resolvedOutput, content);
	return path.relative(rootDirectory, resolvedOutput);
}

const svgOutput = writeOutput(svgOutputPath, svg);
const dataOutput = writeOutput(
	dataOutputPath,
	`${JSON.stringify(
		{
			commits: history,
			endDate: history.at(-1).date,
			head: history.at(-1).hash,
			startDate: history[0].date,
			version: 1,
		},
		null,
		"\t",
	)}\n`,
);

console.log(
	`Wrote ${svgOutput} and ${dataOutput} for ${history.length} commits.`,
);
