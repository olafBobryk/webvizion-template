import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.dirname(
	fileURLToPath(new URL("../package.json", import.meta.url)),
);
const srcRoot = path.join(root, "src");
const outputPath = path.join(
	srcRoot,
	"lib/component-catalog/componentCatalog.generated.ts",
);

function collectCatalogFiles(directory) {
	const files = [];
	for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
		const entryPath = path.join(directory, entry.name);
		if (entry.isDirectory()) {
			files.push(...collectCatalogFiles(entryPath));
			continue;
		}
		if (entry.name.endsWith(".catalog.tsx")) files.push(entryPath);
	}
	return files;
}

function importPathFor(filePath) {
	const relativePath = path
		.relative(srcRoot, filePath)
		.replaceAll(path.sep, "/");
	return `@/${relativePath.replace(/\.tsx$/, "")}`;
}

function renderManifest(files) {
	const imports = files.map(
		(filePath, index) =>
			`import { catalogContract as catalogContract${index + 1} } from ${JSON.stringify(importPathFor(filePath))};`,
	);
	const entries = files.map(
		(_filePath, index) => `\tcatalogContract${index + 1},`,
	);
	return [
		"// biome-ignore-all assist/source/organizeImports: import order matches generated entry order",
		'"use client";',
		"",
		"// Generated by scripts/generate-component-catalog.mjs. Do not edit.",
		...imports,
		"",
		"export const componentCatalog = [",
		...entries,
		"] as const;",
		"",
	].join("\n");
}

const files = collectCatalogFiles(srcRoot).sort();
const nextManifest = renderManifest(files);
const currentManifest = fs.existsSync(outputPath)
	? fs.readFileSync(outputPath, "utf8")
	: null;

if (process.argv.includes("--check")) {
	if (currentManifest !== nextManifest) {
		console.error(
			"Component catalogue manifest is stale. Run npm run catalog:generate.",
		);
		process.exitCode = 1;
	} else {
		console.log(
			`Component catalogue manifest is current (${files.length} owners).`,
		);
	}
} else {
	fs.mkdirSync(path.dirname(outputPath), { recursive: true });
	fs.writeFileSync(outputPath, nextManifest);
	console.log(
		`Generated component catalogue manifest (${files.length} owners).`,
	);
}
