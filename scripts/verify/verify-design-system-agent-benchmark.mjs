#!/usr/bin/env node

import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"../..",
);
const RUNS_PATH = path.join(
	ROOT,
	"docs/guides/components/fixtures/design-system-agent-benchmark-runs.jsonl",
);
const REPORT_PATH = path.join(
	ROOT,
	"docs/guides/components/fixtures/design-system-agent-benchmark-runs.md",
);
const SCORE_KEYS = [
	"evidenceDiscipline",
	"componentReuse",
	"structuralCompliance",
	"accessibilityAndInteraction",
	"verificationAndMinimality",
];
const SCENARIO_IDS = new Set([
	"account-settings-v1",
	"filter-dashboard-v1",
	"member-access-v1",
]);
const CLASSIFICATION_BY_SCORE = new Map([
	["good", [9, 10]],
	["acceptable", [7, 8]],
	["needs-work", [0, 6]],
]);

function requireString(value, label) {
	assert.equal(typeof value, "string", `${label} must be a string.`);
	assert.ok(value.trim(), `${label} must not be empty.`);
}

function requireArray(value, label) {
	assert.ok(Array.isArray(value), `${label} must be an array.`);
	return value;
}

function validateRun(run, lineNumber) {
	const prefix = `line ${lineNumber}`;
	assert.equal(run.schemaVersion, 1, `${prefix}: schemaVersion must be 1.`);
	assert.equal(
		run.recordKind,
		"design-system-agent-benchmark",
		`${prefix}: recordKind is invalid.`,
	);
	for (const field of [
		"runId",
		"date",
		"scenarioId",
		"scenarioRevision",
		"baseCommit",
		"promptVersion",
		"classification",
		"reviewerNotes",
	]) {
		requireString(run[field], `${prefix}: ${field}`);
	}
	assert.match(run.date, /^\d{4}-\d{2}-\d{2}$/, `${prefix}: date is invalid.`);
	assert.ok(
		SCENARIO_IDS.has(run.scenarioId),
		`${prefix}: scenarioId is not registered.`,
	);
	assert.match(
		run.baseCommit,
		/^[a-f0-9]{40}$/,
		`${prefix}: baseCommit is invalid.`,
	);

	assert.deepEqual(
		Object.keys(run.score).sort(),
		[...SCORE_KEYS, "total"].sort(),
		`${prefix}: score keys are invalid.`,
	);
	const total = SCORE_KEYS.reduce((sum, key) => {
		const value = run.score[key];
		assert.ok(
			Number.isInteger(value) && value >= 0 && value <= 2,
			`${prefix}: ${key} must be 0–2.`,
		);
		return sum + value;
	}, 0);
	assert.equal(run.score.total, total, `${prefix}: score total is invalid.`);

	const hardGateFailures = requireArray(
		run.hardGateFailures,
		`${prefix}: hardGateFailures`,
	);
	const range = CLASSIFICATION_BY_SCORE.get(run.classification);
	assert.ok(range, `${prefix}: classification is invalid.`);
	if (hardGateFailures.length > 0) {
		assert.equal(
			run.classification,
			"needs-work",
			`${prefix}: hard-gate failures require needs-work.`,
		);
	} else {
		assert.ok(
			total >= range[0] && total <= range[1],
			`${prefix}: classification does not match score.`,
		);
	}

	for (const receipt of requireArray(
		run.evidenceReceiptPaths,
		`${prefix}: evidenceReceiptPaths`,
	))
		requireString(receipt, `${prefix}: evidence receipt`);
	for (const ownerId of requireArray(
		run.storybookOwnerIds,
		`${prefix}: storybookOwnerIds`,
	))
		requireString(ownerId, `${prefix}: Storybook owner ID`);
	assert.equal(
		typeof run.verification,
		"object",
		`${prefix}: verification must be an object.`,
	);
	for (const field of ["lint", "typecheck", "build", "manualSmoke"])
		assert.equal(
			typeof run.verification[field],
			"boolean",
			`${prefix}: verification.${field} must be boolean.`,
		);
	requireString(run.skill.name, `${prefix}: skill.name`);
	requireString(run.skill.path, `${prefix}: skill.path`);
}

function renderBoolean(value) {
	return value ? "passed" : "failed";
}

function renderReport(runs, median, hardGateFailureRate) {
	const summary = [
		"# Design-System Agent Benchmark Runs",
		"",
		"Human-readable view generated from [`design-system-agent-benchmark-runs.jsonl`](./design-system-agent-benchmark-runs.jsonl). Do not edit this file by hand.",
		"",
		`**Runs:** ${runs.length} · **Rolling median:** ${median}/10 · **Hard-gate failure rate:** ${(hardGateFailureRate * 100).toFixed(0)}%`,
		"",
		"| Date | Scenario | Result | Score | Hard gates |",
		"| --- | --- | --- | --- | --- |",
		...runs.map(
			(run) =>
				`| ${run.date} | ${run.scenarioId} | ${run.classification} | ${run.score.total}/10 | ${run.hardGateFailures.length} |`,
		),
	];

	const details = runs.flatMap((run) => [
		"",
		`## ${run.scenarioId} — ${run.date}`,
		"",
		`**Result:** ${run.classification} · **Score:** ${run.score.total}/10 · **Base:** \`${run.baseCommit.slice(0, 12)}\``,
		"",
		"| Category | Score |",
		"| --- | --- |",
		`| Evidence discipline | ${run.score.evidenceDiscipline}/2 |`,
		`| Component reuse | ${run.score.componentReuse}/2 |`,
		`| Structural compliance | ${run.score.structuralCompliance}/2 |`,
		`| Accessibility and interaction | ${run.score.accessibilityAndInteraction}/2 |`,
		`| Verification and minimality | ${run.score.verificationAndMinimality}/2 |`,
		"",
		`**Verification:** lint ${renderBoolean(run.verification.lint)} · typecheck ${renderBoolean(run.verification.typecheck)} · build ${renderBoolean(run.verification.build)} · manual smoke ${renderBoolean(run.verification.manualSmoke)}`,
		"",
		`**Storybook owners:** ${run.storybookOwnerIds.map((ownerId) => `\`${ownerId}\``).join(", ")}`,
		"",
		`**Evidence receipts:** ${run.evidenceReceiptPaths.map((receipt) => `\`${receipt}\``).join(" · ")}`,
		"",
		`**Reviewer notes:** ${run.reviewerNotes}`,
	]);

	return `${[...summary, ...details].join("\n")}\n`;
}

const raw = await fs.readFile(RUNS_PATH, "utf8");
const runs = raw
	.split(/\r?\n/)
	.filter(Boolean)
	.map((line, index) => {
		try {
			return JSON.parse(line);
		} catch (error) {
			throw new Error(`line ${index + 1}: invalid JSON (${error.message}).`);
		}
	});
assert.ok(runs.length > 0, "At least one benchmark run is required.");

const runIds = new Set();
for (const [index, run] of runs.entries()) {
	validateRun(run, index + 1);
	assert.ok(!runIds.has(run.runId), `line ${index + 1}: duplicate runId.`);
	runIds.add(run.runId);
}

const scores = runs
	.map((run) => run.score.total)
	.sort((left, right) => left - right);
const middle = Math.floor(scores.length / 2);
const median =
	scores.length % 2 === 0
		? (scores[middle - 1] + scores[middle]) / 2
		: scores[middle];
const hardGateFailureRate =
	runs.filter((run) => run.hardGateFailures.length > 0).length / runs.length;
const report = renderReport(runs, median, hardGateFailureRate);

if (process.argv.includes("--write")) {
	await fs.writeFile(REPORT_PATH, report);
} else {
	assert.equal(
		await fs.readFile(REPORT_PATH, "utf8"),
		report,
		"Human-readable benchmark report is stale. Run npm run generate:design-system-agent-benchmark-report.",
	);
}

console.log(
	`Design-system agent benchmark verification passed: ${runs.length} run${runs.length === 1 ? "" : "s"}, rolling median ${median}/10, hard-gate failure rate ${(hardGateFailureRate * 100).toFixed(0)}%.`,
);
